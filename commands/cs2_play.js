// Intentar cargar cookies/tokens de YouTube de forma automática para evitar bloqueos de IP
try {
  const tokenPath = path.join(process.cwd(), 'youtube.data.json');
  if (fs.existsSync(tokenPath)) {
    const rawData = fs.readFileSync(tokenPath, 'utf8');
    const tokenData = JSON.parse(rawData);
    
    let cookieString = '';
    let userAgent = '';
    
    if (Array.isArray(tokenData)) {
      cookieString = tokenData.map(c => `${c.name}=${c.value}`).join('; ');
    } else if (tokenData && typeof tokenData === 'object') {
      if (Array.isArray(tokenData.cookie)) {
        cookieString = tokenData.cookie.map(c => `${c.name}=${c.value}`).join('; ');
      } else {
        cookieString = tokenData.cookie || '';
      }
      userAgent = tokenData['user-agent'] || tokenData.userAgent || '';
      
    }

    const youtubeAuth = { cookie: cookieString };

    await play.setToken({
      youtube: youtubeAuth,
      useragent: userAgent
    });
    logger.success('🔑 Cookies de YouTube cargadas exitosamente en play-dl desde youtube.data.json');
  } else {
    logger.warn('⚠️ No se encontró youtube.data.json. Si experimentas bloqueos de YouTube (ERR_INVALID_URL), crea este archivo con tus cookies.');
  }
} catch (err) {
  logger.error('❌ Error al intentar cargar cookies de YouTube:', err.message);
}

