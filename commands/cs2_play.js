function resolveYtDlpPath() {
  if (process.env.YT_DLP_PATH) return process.env.YT_DLP_PATH;

  const localExecutable = path.join(process.cwd(), process.platform === 'win32' ? 'yt-dlp.exe' : 'yt-dlp');
  return fs.existsSync(localExecutable) ? localExecutable : 'yt-dlp';
}

function tryAutoUpdateYtDlp() {
  try {
    const bin = resolveYtDlpPath();
    const updater = spawn(bin, ['-U'], {
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });

    let output = '';
    updater.stdout?.on('data', chunk => {
      output += chunk;
    });
    updater.stderr?.on('data', chunk => {
      output += chunk;
    });

    updater.on('close', code => {
      const trimmed = output.trim();
      const lastLine = trimmed.split(/\r?\n/).pop() || '';
      if (code === 0) {
        logger.info(`🔄 [yt-dlp] ${lastLine || 'yt-dlp verificado y al día.'}`);
      } else if (trimmed) {
        logger.warn(`⚠️ [yt-dlp] Comprobación de actualización finalizó con código ${code}: ${lastLine}`);
      }
    });

    updater.on('error', err => {
      logger.warn(`⚠️ [yt-dlp] No se pudo comprobar actualizaciones: ${err.message}`);
    });
  } catch (err) {
    logger.warn(`⚠️ [yt-dlp] Error ejecutando autoupdate: ${err.message}`);
  }
}

// Ejecutar comprobación de actualización al inicializar el módulo
tryAutoUpdateYtDlp();

function stopCurrentDownloader(queue) {
  const downloader = queue?.currentDownloader;
  if (!downloader) return;

  queue.currentDownloader = null;
  if (!downloader.killed && downloader.exitCode === null) {
    downloader.kill();
  }
}

function getValidCookiesPath() {
  const cookiesPath = process.env.YOUTUBE_COOKIES_PATH || path.join(process.cwd(), 'cookies.txt');
  if (!fs.existsSync(cookiesPath)) {
    return null;
  }
  try {
    const stats = fs.statSync(cookiesPath);
    if (stats.size === 0) {
      logger.warn(`El archivo de cookies "${cookiesPath}" está vacío (0 bytes). Se omitirá.`);
      return null;
    }
    const fd = fs.openSync(cookiesPath, 'r');
    const buf = Buffer.alloc(512);
    const bytesRead = fs.readSync(fd, buf, 0, 512, 0);
    fs.closeSync(fd);
    const header = buf.toString('utf8', 0, bytesRead);
    const firstLine = header.split(/\r?\n/).find(l => l.trim().length > 0) || '';
    if (!/^#(?: Netscape| HTTP)? Cookie File|^# Generated by Wget/i.test(firstLine.trim())) {
      logger.warn(`El archivo de cookies "${cookiesPath}" no tiene el formato Netscape requerido (# Netscape HTTP Cookie File). Se omitirá.`);
      return null;
    }
    return cookiesPath;
  } catch (err) {
    logger.warn(`No se pudo verificar el archivo de cookies "${cookiesPath}": ${err.message}`);
    return null;
  }
}

async function createYoutubeAudioStream(url) {
  const args = [
    '--no-playlist',
    '--quiet',
    '--no-progress',
    '--extractor-args', 'youtube:player_client=android,android_vr,web',
    '--format', 'bestaudio[ext=webm][acodec=opus]/bestaudio/18/best',
    '--output', '-',
  ];

  const validCookies = getValidCookiesPath();
  if (validCookies) {
    args.push('--cookies', validCookies);
  }

  args.push(url);

  const downloader = spawn(resolveYtDlpPath(), args, {
    stdio: ['ignore', 'pipe', 'pipe'],
    windowsHide: true,
  });

  let stderr = '';
  downloader.stderr.setEncoding('utf8');
  downloader.stderr.on('data', chunk => {
    stderr = `${stderr}${chunk}`.slice(-8000);
  });

  await new Promise((resolve, reject) => {
    let settled = false;

    const cleanup = () => {
      clearTimeout(startupTimeout);
      downloader.stdout.off('readable', onReadable);
      downloader.off('error', onError);
      downloader.off('close', onClose);
    };
    const settle = callback => value => {
      if (settled) return;
      settled = true;
      cleanup();
      callback(value);
    };
    const onReadable = settle(resolve);
    const onError = settle(error => reject(new Error(`No se pudo ejecutar yt-dlp: ${error.message}`)));
    const onClose = settle(code => {
      const details = stderr.trim().split(/\r?\n/).slice(-2).join(' ') || `codigo ${code}`;
      reject(new Error(`yt-dlp no pudo extraer el audio: ${details}`));
    });
    const startupTimeout = setTimeout(() => {
      downloader.kill();
      const details = stderr.trim().split(/\r?\n/).slice(-3).join(' ') || 'sin detalles de stderr';
      onError(new Error(`no entrego audio dentro del tiempo esperado (60s). Detalle: ${details}`));
    }, 60000);

    downloader.stdout.once('readable', onReadable);
    downloader.once('error', onError);
    downloader.once('close', onClose);
  });

  return { downloader, getStderr: () => stderr.trim() };
}
function buildMusicControls(guildId, queue, disabled = false) {
  const isPaused = queue.player.state.status === AudioPlayerStatus.Paused;

  return new ActionRowBuilder().addComponents(
    new ButtonBuilder()
      .setCustomId('music_toggle:' + guildId)
      .setLabel(isPaused ? 'Reanudar' : 'Pausar')
      .setEmoji(isPaused ? '\u25B6\uFE0F' : '\u23F8\uFE0F')
      .setStyle(isPaused ? ButtonStyle.Success : ButtonStyle.Secondary)
      .setDisabled(disabled),
    new ButtonBuilder()
      .setCustomId('music_skip:' + guildId)
      .setLabel('Saltar')
      .setEmoji('\u23ED\uFE0F')
      .setStyle(ButtonStyle.Primary)
      .setDisabled(disabled),
    new ButtonBuilder()
      .setCustomId('music_queue:' + guildId)
      .setLabel('Cola')
      .setEmoji('\uD83D\uDCCB')
      .setStyle(ButtonStyle.Secondary)
      .setDisabled(disabled),
    new ButtonBuilder()
      .setCustomId('music_clear:' + guildId)
      .setLabel('Limpiar')
      .setEmoji('\uD83E\uDDF9')
      .setStyle(ButtonStyle.Secondary)
      .setDisabled(disabled),
    new ButtonBuilder()
      .setCustomId('music_stop:' + guildId)
      .setLabel('Detener')
      .setEmoji('\u23F9\uFE0F')
      .setStyle(ButtonStyle.Danger)
      .setDisabled(disabled)
  );
}

function buildMusicEmbed(queue, status = 'Reproduciendo') {
  const song = queue.currentSong;
  const isPaused = queue.player.state.status === AudioPlayerStatus.Paused;
  const color = ['Detenido', 'Desconectado', 'Cola finalizada'].includes(status)
    ? 0x747F8D
    : isPaused ? 0xF1C40F : 0x2ECC71;

  const embed = new EmbedBuilder()
    .setColor(color)
    .setTitle('\uD83C\uDFB5 ' + (isPaused ? 'Reproduccion pausada' : status))
    .setTimestamp();

  if (song) {
    embed
      .setDescription('[' + song.title.slice(0, 200) + '](' + song.url + ')')
      .addFields(
        { name: 'Solicitado por', value: '<@' + song.requestedBy + '>', inline: true },
        { name: 'Canciones en cola', value: String(queue.songs.length), inline: true },
        { name: 'Canal de voz', value: '<#' + queue.voiceChannelId + '>', inline: true }
      );
  } else {
    embed.setDescription(status === 'Detenido'
      ? 'La reproduccion fue detenida y la cola fue eliminada.'
      : 'No quedan canciones pendientes.');
  }

  return embed.setFooter({ text: 'Los controles funcionan para usuarios del mismo canal de voz y moderadores.' });
}

async function updateMusicPanel(queue, guildId, { disabled = false, status = 'Reproduciendo' } = {}) {
  const payload = {
    embeds: [buildMusicEmbed(queue, status)],
    components: [buildMusicControls(guildId, queue, disabled)],
  };

  if (queue.controlMessage) {
    try {
      await queue.controlMessage.edit(payload);
      return;
    } catch (error) {
      logger.warn('No se pudo actualizar el panel de musica anterior: ' + error.message);
      queue.controlMessage = null;
    }
  }

  if (!disabled && queue.textChannel) {
    queue.controlMessage = await queue.textChannel.send(payload).catch(error => {
      logger.warn('No se pudo crear el panel de musica: ' + error.message);
      return null;
    });
  }
}

function canControlMusic(interaction, queue) {
  const sameVoiceChannel = interaction.member?.voice?.channelId === queue.voiceChannelId;
  const isModerator = interaction.memberPermissions?.has(PermissionFlagsBits.ManageGuild) ||
    interaction.memberPermissions?.has(PermissionFlagsBits.Administrator);
  return sameVoiceChannel || isModerator;
}

function formatQueue(queue) {
  const upcoming = queue.songs.slice(0, 10);
  const lines = [];
  if (queue.currentSong) lines.push('**Ahora:** ' + queue.currentSong.title);
  if (upcoming.length > 0) {
    lines.push('', ...upcoming.map((song, index) => (index + 1) + '. ' + song.title));
  }
  if (queue.songs.length > upcoming.length) {
    lines.push('', '...y ' + (queue.songs.length - upcoming.length) + ' canciones mas.');
  }
  return lines.join('\n').slice(0, 1900) || 'La cola esta vacia.';
}


