async function processPlayCommand(interaction, link) {
  const { guildId, channelId, member, guild } = interaction;
  
  // 1. Obtener configuración y validar canal de texto
  const config = await getEffectiveConfigForGuild(guildId);
  const musicChannelId = config.discordMusicChannelId;

  if (musicChannelId && musicChannelId.trim() !== '' && channelId !== musicChannelId) {
    return interaction.reply({ 
      content: `❌ Este comando solo se puede usar en el canal de música autorizado: <#${musicChannelId}>`, 
      flags: MessageFlags.Ephemeral 
    });
  }

  // 2. Validar que el usuario esté en un canal de voz
  const voiceChannel = member.voice.channel;
  if (!voiceChannel) {
    return interaction.reply({ 
      content: '❌ Debes estar en un canal de voz para usar este comando.', 
      flags: MessageFlags.Ephemeral 
    });
  }

  // 3. Validar permisos del bot para unirse al canal de voz
  const permissions = voiceChannel.permissionsFor(interaction.client.user);
  if (!permissions.has('Connect') || !permissions.has('Speak')) {
    return interaction.reply({ 
      content: '❌ No tengo permisos para unirme y hablar en tu canal de voz.', 
      flags: MessageFlags.Ephemeral 
    });
  }

  // Diferir la respuesta efímeramente para que solo el usuario que ejecutó el comando la vea
  await interaction.deferReply({ flags: MessageFlags.Ephemeral });

  // 4. Validar enlace de YouTube o realizar búsqueda
  const validation = play.yt_validate(link);

  try {
    let songsToAdd = [];
    let isPlaylist = false;
    let playlistTitle = '';

    try {
      const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('YouTube API Timeout')), ms));

      if (validation === 'playlist') {
        isPlaylist = true;
        const playlist = await Promise.race([
          play.playlist_info(link, { incomplete: true }),
          timeout(4000)
        ]);
        playlistTitle = playlist.title;
        const videos = await playlist.all_videos();
        songsToAdd = videos.slice(0, 100).map((video, idx) => ({
          id: `${Date.now()}_${idx}_${Math.random().toString(36).substring(2, 5)}`,
          title: video.title,
          url: video.url || (video.id ? `https://www.youtube.com/watch?v=${video.id}` : null),
          requestedBy: interaction.user.id
        })).filter(song => song.url);
      } else if (validation === 'video') {
        let videoTitle = 'Cancion de YouTube';
        try {
          const videoInfo = await Promise.race([
            play.video_basic_info(link),
            timeout(10000)
          ]);
          videoTitle = videoInfo.video_details?.title || videoTitle;
        } catch (metadataError) {
          logger.warn(`No se pudieron obtener los metadatos de "${link}"; se intentara reproducir directamente con yt-dlp: ${metadataError.message}`);
        }
        songsToAdd.push({
          id: `${Date.now()}_${Math.random().toString(36).substring(2, 5)}`,
          title: videoTitle,
          url: link,
          requestedBy: interaction.user.id
        });
      } else {
        // Búsqueda de YouTube
        const searchResults = await Promise.race([
          play.search(link, { limit: 1 }),
          timeout(4000)
        ]);
        if (searchResults.length > 0) {
          const video = searchResults[0];
          const url = video.url || (video.id ? `https://www.youtube.com/watch?v=${video.id}` : null);
          if (url) {
            songsToAdd.push({
              id: `${Date.now()}_${Math.random().toString(36).substring(2, 5)}`,
              title: video.title,
              url: url,
              requestedBy: interaction.user.id
            });
          }
        } else {
          return interaction.editReply('❌ No se encontraron resultados en YouTube para tu búsqueda.');
        }
      }
    } catch (ytError) {
      logger.error(`Error de extracción en YouTube para "${link}": ${ytError.message || ytError}`);
      return interaction.editReply(`❌ No se pudo procesar la solicitud de YouTube: ${ytError.message || 'Error desconocido'}`);
    }

    if (songsToAdd.length === 0) {
      return interaction.editReply('❌ No se encontraron canciones para reproducir.');
    }

    // 5. Obtener o crear la cola de reproduccion
    let queue = queues.get(guildId);
    if (queue && queue.voiceChannelId !== voiceChannel.id) {
      return interaction.editReply('El bot ya esta reproduciendo musica en otro canal de voz de este servidor.');
    }
    if (!queue) {
      // Conectarse al canal de voz
      const connection = joinVoiceChannel({
        channelId: voiceChannel.id,
        guildId: guildId,
        adapterCreator: guild.voiceAdapterCreator,
      });

      try {
        await entersState(connection, VoiceConnectionStatus.Ready, 15000);
      } catch (voiceError) {
        connection.destroy();
        logger.error('No se pudo establecer la conexion de voz:', voiceError);
        return interaction.editReply('No pude conectarme al canal de voz. Verifica mis permisos e intenta nuevamente.');
      }

      const player = createAudioPlayer();
      connection.subscribe(player);

      queue = {
        connection,
        player,
        songs: [],
        currentSong: null,
        currentDownloader: null,
        timeoutId: null,
        textChannel: interaction.channel,
        voiceChannelId: voiceChannel.id,
        controlMessage: null,
        isStarting: false,
        stopping: false,
      };

      queues.set(guildId, queue);

      // Manejadores de eventos de la conexión
      connection.on('stateChange', (oldState, newState) => {
        logger.info(`Conexión de voz para guild ${guildId}: ${oldState.status} -> ${newState.status}`);
      });

      connection.on(VoiceConnectionStatus.Disconnected, async () => {
        try {
          await Promise.race([
            entersState(connection, VoiceConnectionStatus.Signalling, 5000),
            entersState(connection, VoiceConnectionStatus.Connecting, 5000),
          ]);
        } catch (error) {
          connection.destroy();
        }
      });

      connection.on(VoiceConnectionStatus.Destroyed, () => {
        const finalStatus = queue.stopping ? 'Detenido' : 'Desconectado';
        queue.stopping = true;
        if (queue.timeoutId) clearTimeout(queue.timeoutId);
        stopCurrentDownloader(queue);
        if (queue.controlMessage) {
          queue.controlMessage.delete().catch(() => {});
          queue.controlMessage = null;
        }
        queues.delete(guildId);
      });

      // Manejador del reproductor
      player.on('stateChange', (oldState, newState) => {
        logger.info(`Reproductor de audio para guild ${guildId}: ${oldState.status} -> ${newState.status}`);
      });

      player.on(AudioPlayerStatus.Idle, () => {
        if (queue.stopping) return;
        queue.currentDownloader = null;
        queue.currentSong = null;
        playNextSong(guildId).catch(error => logger.error('No se pudo avanzar la cola de musica:', error));
      });

      player.on('error', error => {
        logger.error('Error en el reproductor de audio para guild ' + guildId + ':', error);
        stopCurrentDownloader(queue);
        queue.textChannel.send('Ocurrio un error de audio. Se intentara reproducir la siguiente cancion.').catch(() => {});
      });
    }

    // Agregar canciones a la cola
    queue.textChannel = interaction.channel;
    queue.songs.push(...songsToAdd);

    // Si ya hay algo reproduciéndose
    const isCurrentlyPlaying = queue.currentSong || queue.player.state.status !== AudioPlayerStatus.Idle;

    if (isCurrentlyPlaying) {
      if (isPlaylist) {
        await interaction.editReply('Se agregaron **' + songsToAdd.length + '** canciones de la playlist **"' + playlistTitle + '"** a la cola.');
      } else {
        await interaction.editReply('Se agrego **"' + songsToAdd[0].title + '"** a la cola (posicion #' + queue.songs.length + ').');
      }
      await updateMusicPanel(queue, guildId);
    } else {
      await playNextSong(guildId);
      await interaction.editReply(queue.currentSong
        ? 'Reproduciendo **"' + queue.currentSong.title + '"**. Usa el panel publico para controlarla.'
        : 'No se pudo iniciar ninguna de las canciones solicitadas.'
      );
    }

  } catch (error) {
    logger.error('Error procesando el comando cs2_play:', error);
    await interaction.editReply('❌ Ocurrió un error al intentar procesar el enlace de YouTube.');
  }
}

function cleanTitleForSearch(title) {
  if (!title) return '';
  return title
    .replace(/\[[^\]]+\]/g, '') // remove brackets [Lyrics]
    .replace(/\([^)]+\)/g, '') // remove parentheses (Official Video)
    .replace(/official\s*(video|audio|mv|lyric\s*video)/gi, '')
    .replace(/video\s*oficial/gi, '')
    .replace(/clip\s*oficial/gi, '')
    .replace(/hd/gi, '')
    .replace(/\|/g, ' ') // replace pipes with space
    .replace(/\s+/g, ' ') // collapse spaces
    .trim();
}

async function playNextSong(guildId) {
  const queue = queues.get(guildId);
  if (!queue || queue.stopping || queue.isStarting) return;

  queue.isStarting = true;
  if (queue.timeoutId) {
    clearTimeout(queue.timeoutId);
    queue.timeoutId = null;
  }

  try {
    while (queue.songs.length > 0 && !queue.stopping) {
      const nextSong = queue.songs.shift();
      queue.currentSong = nextSong;

      try {
        const { downloader, getStderr } = await createYoutubeAudioStream(nextSong.url);
        if (queues.get(guildId) !== queue || queue.stopping) {
          downloader.kill();
          return;
        }

        queue.currentDownloader = downloader;
        downloader.once('close', code => {
          if (code !== 0 && !downloader.killed) {
            const details = getStderr() || 'yt-dlp termino con codigo ' + code;
            logger.error('yt-dlp fallo para "' + nextSong.title + '": ' + details);
          }
        });

        const resource = createAudioResource(downloader.stdout, {
          inputType: StreamType.Arbitrary,
        });
        queue.player.play(resource);
        await updateMusicPanel(queue, guildId);

        return;
      } catch (error) {
        stopCurrentDownloader(queue);
        queue.currentSong = null;
        logger.error('Error reproduciendo cancion "' + nextSong.title + '":', error);
        await queue.textChannel.send(
          'No se pudo reproducir **"' + nextSong.title + '"**: ' + (error.message || error)
        ).catch(() => {});
      }
    }

    queue.currentSong = null;
    if (queue.controlMessage) {
      await queue.controlMessage.delete().catch(() => {});
      queue.controlMessage = null;
    }
    queue.timeoutId = setTimeout(() => {
      const activeQueue = queues.get(guildId);
      if (activeQueue === queue && !queue.currentSong && queue.songs.length === 0) {
        queue.textChannel.send('Me desconecte del canal de voz por 5 minutos de inactividad.').catch(() => {});
        queue.connection.destroy();
      }
    }, 5 * 60 * 1000);
  } finally {
    queue.isStarting = false;
  }
}

export async function handleMusicButton(interaction) {
  const control = interaction.customId.slice('music_'.length);
  const separatorIndex = control.indexOf(':');
  const action = separatorIndex === -1 ? '' : control.slice(0, separatorIndex);
  const guildId = separatorIndex === -1 ? '' : control.slice(separatorIndex + 1);

  if (!guildId || guildId !== interaction.guildId) {
    return interaction.reply({ content: 'Este control ya no es valido.', flags: MessageFlags.Ephemeral });
  }

  const queue = queues.get(guildId);
  if (!queue || !queue.currentSong) {
    return interaction.reply({ content: 'No hay ninguna cancion activa.', flags: MessageFlags.Ephemeral });
  }

  if (!canControlMusic(interaction, queue)) {
    return interaction.reply({
      content: 'Debes estar en el mismo canal de voz que el bot para utilizar estos controles.',
      flags: MessageFlags.Ephemeral,
    });
  }

  if (action === 'toggle') {
    if (queue.player.state.status === AudioPlayerStatus.Playing) {
      queue.player.pause();
    } else if (queue.player.state.status === AudioPlayerStatus.Paused) {
      queue.player.unpause();
    } else {
      return interaction.reply({ content: 'El reproductor no se puede pausar en este momento.', flags: MessageFlags.Ephemeral });
    }
    await interaction.deferUpdate();
    await updateMusicPanel(queue, guildId);
    return;
  }

  if (action === 'skip') {
    await interaction.reply({ content: 'Saltando la cancion actual...', flags: MessageFlags.Ephemeral });
    stopCurrentDownloader(queue);
    queue.player.stop(true);
    return;
  }

  if (action === 'queue') {
    return interaction.reply({ content: formatQueue(queue), flags: MessageFlags.Ephemeral });
  }

  if (action === 'clear') {
    const removed = queue.songs.length;
    queue.songs.length = 0;
    await interaction.reply({ content: 'Se eliminaron ' + removed + ' canciones pendientes.', flags: MessageFlags.Ephemeral });
    await updateMusicPanel(queue, guildId);
    return;
  }

  if (action === 'stop') {
    await interaction.reply({ content: 'Reproduccion detenida y cola eliminada.', flags: MessageFlags.Ephemeral });
    queue.stopping = true;
    queue.songs.length = 0;
    stopCurrentDownloader(queue);
    queue.player.stop(true);
    queue.currentSong = null;
    if (queue.controlMessage) {
      await queue.controlMessage.delete().catch(() => {});
      queue.controlMessage = null;
    }
    if (queue.connection.state.status !== VoiceConnectionStatus.Destroyed) {
      queue.connection.destroy();
    }
    return;
  }

  return interaction.reply({ content: 'Control de musica desconocido.', flags: MessageFlags.Ephemeral });
}
